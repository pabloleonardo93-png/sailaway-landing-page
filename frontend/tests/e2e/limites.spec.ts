import { test, expect, abrir, caixa, conferirArquivosProtegidos } from './apoio'

test.use({ isMobile: true, hasTouch: true })
test.beforeAll(() => conferirArquivosProtegidos())
test.afterAll(() => conferirArquivosProtegidos())

test('Toque mantém CTA legível e abre somente a âncora local', async ({ page }) => {
  await abrir(page)
  expect(await page.evaluate(() => matchMedia('(hover: none) and (pointer: coarse)').matches)).toBe(true)
  const botao = page.locator('.hero .button')
  const antes = await caixa(botao)
  await botao.tap()
  await expect(page).toHaveURL(/#captacao$/)
  await expect(botao).toHaveCSS('color', 'rgb(255, 189, 74)')
  await expect.poll(async () => (await caixa(botao)).width).toBe(antes.width)
  await expect.poll(async () => (await caixa(botao)).height).toBe(antes.height)
  await page.getByRole('button', { name: 'Abrir menu' }).tap()
  await expect(page.locator('.site-nav')).toBeVisible()
  await page.getByRole('button', { name: 'Fechar menu' }).tap()
  await expect(page.locator('.site-nav')).not.toBeVisible()
  await page.setViewportSize({ width: 844, height: 390 })
  await expect(page.locator('.como-funciona')).toHaveAttribute('data-timeline', 'vertical')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.locator('.como-funciona')).toHaveAttribute('data-timeline', 'vertical')
})

test('Falha local de vídeo mantém o poster do globo disponível', async ({ page, context }, testInfo) => {
  testInfo.annotations.push({ type: 'recurso-indisponivel', description: '/videos/sailaway-globo-web.mp4' })
  await context.route('**/videos/sailaway-globo-web.mp4', rota => rota.fulfill({ status: 404, body: '' }))
  await abrir(page)
  await page.locator('.world-connections__scene').scrollIntoViewIfNeeded()
  await expect.poll(() => page.locator('.world-connections__video').evaluate(e => (e as HTMLVideoElement).error?.code ?? 0)).toBeGreaterThan(0)
  await expect(page.locator('.world-connections__video')).not.toHaveClass(/is-ready/)
  const poster = page.locator('.world-connections__poster')
  await expect(poster).toBeVisible()
  expect(await poster.evaluate(e => (e as HTMLImageElement).complete && (e as HTMLImageElement).naturalWidth > 0)).toBe(true)
  await expect(poster).toHaveAttribute('src', '/images/sailaway-globo-poster.webp')
})
