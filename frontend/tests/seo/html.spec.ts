import { readFileSync } from 'node:fs'
import { test, expect, abrir, conferirArquivosProtegidos } from '../e2e/apoio'

test.beforeAll(() => conferirArquivosProtegidos())
test.afterAll(() => conferirArquivosProtegidos())

test('Homepage SSG preserva semântica, metadados únicos, âncoras e hidratação', async ({ page }, testInfo) => {
  await abrir(page)
  await expect(page).toHaveTitle('SAILAWAY | Planejamento de viagens e rede de membros')
  await expect(page.locator('html')).toHaveAttribute('lang', 'pt-BR')
  await expect(page.locator('head meta[charset]')).toHaveCount(1)
  await expect(page.locator('head meta[name="viewport"]')).toHaveCount(1)
  await expect(page.locator('head title')).toHaveCount(1)
  await expect(page.locator('head meta[name="description"]')).toHaveCount(1)
  await expect(page.locator('head meta[name="description"]')).toHaveAttribute('content', /planejamento de viagens.*participação como membro/)
  for (const campo of ['og:title', 'og:description', 'og:type', 'og:locale', 'og:site_name']) await expect(page.locator(`head meta[property="${campo}"]`)).toHaveCount(1)
  for (const campo of ['twitter:card', 'twitter:title', 'twitter:description']) await expect(page.locator(`head meta[name="${campo}"]`)).toHaveCount(1)
  await expect(page.locator('link[rel="canonical"], meta[property="og:url"], meta[property="og:image"], meta[name="robots"], script[type="application/ld+json"]')).toHaveCount(0)
  await expect(page.locator('meta[property^="og:image"], meta[name^="twitter:image"]')).toHaveCount(0)
  await expect(page.locator('meta[name="twitter:card"]')).toHaveAttribute('content', 'summary')
  expect(await page.evaluate(() => performance.getEntriesByType('resource').some(e => e.name.includes('/images/social/')))).toBe(false)
  await expect(page.locator('main h1')).toHaveCount(1)
  await expect(page.locator('h2')).toHaveCount(8)
  await expect(page.locator('h3')).toHaveCount(16)
  await expect(page.locator('.institucional__benefit')).toHaveCount(4)
  await expect(page.locator('.faq__answer')).toHaveCount(6)
  await expect(page.locator('#root')).toHaveAttribute('data-ssg', 'true')
  expect(await page.locator('a[href^="#"]').evaluateAll(links => links.every(link => document.getElementById(link.getAttribute('href')!.slice(1))))).toBe(true)
  expect(await page.locator('img').evaluateAll(imagens => imagens.every(img => img.hasAttribute('alt')))).toBe(true)
  const publico = await page.request.get('/').then(r => r.text())
  expect(publico).toBe(readFileSync('dist/index.html', 'utf8'))
  expect(publico).not.toMatch(/G-[A-Z0-9]{6,}|googletagmanager\.com|google-analytics\.com|gtag\(/)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const antes = await page.locator('head').innerHTML()
  await page.locator('#faq-pergunta-2').click()
  await expect(page.locator('#faq-pergunta-2')).toHaveAttribute('aria-expanded', 'true')
  expect(await page.locator('head').innerHTML()).toBe(antes)
  await testInfo.attach('seo-homepage', { body: publico, contentType: 'text/html' })
})
